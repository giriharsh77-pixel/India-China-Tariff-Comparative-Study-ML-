"""Fill the RESULTS block of README.md from outputs/results_summary.json."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = json.loads((ROOT / "outputs/results_summary.json").read_text())
K, T, F = R["k"], R["test_year_last"], R["forward_year"]
S = {(r["method"], r["k"]): r for r in R["summary"]}
U = {r["k"]: r for r in R["universe"]}[K]
b, m, n = S[("Historical momentum (baseline)", K)], S[("ML ranking", K)], S[("ML without tariff features", K)]
yrs = [f["decision_year"] for f in R["folds"] if f["decision_year"] <= T]
pct = lambda x: f"{int(100 * x + 0.5 + 1e-9) if x >= 0 else -int(-100 * x + 0.5 + 1e-9)}%"  # round half up (matches deck)
sg = lambda x: f"{x:+.2f}"

block = f"""**Headline results** (rolling-origin backtest, held-out decision years {yrs[0]}–{T}, outcomes {yrs[0] + 1}–{T + 1}, K = {K}):

| Metric | Historical baseline | ML model | ML without tariffs | Random pick |
|---|---:|---:|---:|---:|
| Precision@{K} (share of picks where India's share rose) | {pct(b['precision_at_k'])} | {pct(m['precision_at_k'])} | {pct(n['precision_at_k'])} | {pct(U['universe_precision'])} |
| Average future market-share change@{K} (pp) | {sg(b['mean_d_share_pp_at_k'])} | {sg(m['mean_d_share_pp_at_k'])} | {sg(n['mean_d_share_pp_at_k'])} | {sg(U['universe_mean_d_share_pp'])} |
| Average future export growth@{K} (log) | {sg(b['mean_export_growth_log_at_k'])} | {sg(m['mean_export_growth_log_at_k'])} | {sg(n['mean_export_growth_log_at_k'])} | {sg(U['universe_mean_export_growth_log'])} |
| NDCG@{K} | {b['ndcg_at_k']:.3f} | {m['ndcg_at_k']:.3f} | {n['ndcg_at_k']:.3f} | {U['random_ndcg']:.3f} |

Momentum is worse than a random pick (fast growers mean-revert); ML avoids that trap but beats random only narrowly overall
(it underperformed in the 2024→2025 fold, the year of the US tariff shock), and tariff features add no measurable predictive value.

Dataset: {R['dataset']['n_rows']:,} candidate rows ({R['dataset']['n_markets']} markets × {R['dataset']['n_products']} HS6 products,
decision years {R['dataset']['years'][0]}–{R['dataset']['years'][1]}). Selected model: {R['selected_model']['model'].upper()}.
Live {F} shortlists: `outputs/rankings/top10_ml_{F}.csv` and `top10_baseline_{F}.csv`. All numbers are regenerated by the pipeline."""

readme = (ROOT / "README.md").read_text(encoding="utf-8")
readme = re.sub(r"<!-- RESULTS:START -->.*<!-- RESULTS:END -->",
                "<!-- RESULTS:START -->\n" + block + "\n<!-- RESULTS:END -->", readme, flags=re.S)
(ROOT / "README.md").write_text(readme, encoding="utf-8")
print("README results block updated")
